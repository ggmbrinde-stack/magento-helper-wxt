// Feature: last-resort product lookup through the admin grid (AJAX), plus the
// full child list read from the open product's Configurations matrix.
import type {
  ResolverChild,
  SearchMagentoResponse,
} from '../../../core/messages';
import { findConfigSection, isCollapsed } from '../../shared/config-section';
import { readPageSku } from '../../shared/magentoForm';
import { readAdminFacts } from './adminFacts';

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Expand the Configurations section and wait for its rows.
 *
 * Only used on a tab the extension opened and will close itself: on the
 * operator's own tab a collapsed section is reported, never touched.
 */
async function expandConfigSection(section: Element): Promise<void> {
  const collapsible = section.classList.contains('admin__collapsible-block-wrapper')
    ? section
    : section.closest('.admin__collapsible-block-wrapper');
  const title = collapsible?.querySelector<HTMLElement>('.admin__collapsible-title');
  title?.click();
  const start = Date.now();
  while (Date.now() - start < 2500) {
    const table = findConfigSection()?.querySelector('table');
    if (table && table.querySelectorAll('tbody tr').length > 0) return;
    await sleep(150);
  }
}

const CHILD_LINK = 'a[href*="/catalog/product/edit/id/"]';

interface ConfigChildren {
  children: ResolverChild[];
  reason: string;
}

/** One lazy-loaded grid page, as the listing provider returns it. */
interface GridItem {
  sku?: string;
  entity_id?: string | number;
  id?: string | number;
  /** The configurable parent's SKU - the grid exposes it as its own column. */
  parent_sku?: string;
  /** Magento product type (`simple`, `configurable`, `bundle`, …). */
  type_id?: string;
  /** Status column: `1`/`2`, `Enabled`/`Disabled`, or a boolean. */
  status?: unknown;
  /** Some listing providers nest the row under `data`. */
  data?: GridItem;
}

/**
 * Column value off a grid row, whatever shape the provider used.
 *
 * Magento's `mui/index/render` returns rows keyed by column name, but other
 * providers (and some third-party grids) wrap the row in `data` or hand back a
 * rendered `"<td>...</td>"` blob. Reading only `item.sku` silently produced a
 * child list with no SKUs at all, which is what the resolver table showed.
 */
function cellText(
  item: GridItem | undefined,
  key: 'sku' | 'entity_id' | 'id' | 'status' | 'parent_sku' | 'type_id',
): string {
  if (!item) return '';
  const raw = item[key] ?? item.data?.[key];
  if (raw === undefined || raw === null) return '';
  return String(raw)
    .replace(/<[^>]*>/g, '')
    .replace(/&nbsp;/g, ' ')
    .trim();
}

/** Row id: `entity_id` first, then the document `id`. */
function itemId(item: GridItem): string {
  return cellText(item, 'entity_id') || cellText(item, 'id');
}

/**
 * The product grid's Status column, normalised to the admin's own words.
 *
 * Magento returns `1`/`2` in JSON, `Enabled`/`Disabled` when the column is
 * rendered with its option labels, and `true`/`false` in some themes. An
 * unrecognised value is passed through untouched rather than guessed at, so the
 * resolver never claims a product is enabled without evidence.
 */
function statusLabel(raw: unknown): string {
  if (raw === undefined || raw === null) return '';
  if (typeof raw === 'boolean') return raw ? 'Enabled' : 'Disabled';
  const text = String(raw).replace(/<[^>]*>/g, '').trim();
  if (!text) return '';
  if (/^(1|true|enabled|enable|active)$/i.test(text)) return 'Enabled';
  if (/^(2|false|disabled|disable|inactive)$/i.test(text)) return 'Disabled';
  return text;
}

/** Status cell -> the child's `enabled` flag; undefined when unreported. */
function statusEnabled(raw: unknown): boolean | undefined {
  const label = statusLabel(raw);
  if (label === 'Enabled') return true;
  if (label === 'Disabled') return false;
  return undefined;
}

/**
 * A grid key the admin itself emitted for this exact route.
 *
 * Magento's URL secret is per route (`_getSecretKey($routePath, $params)`), so
 * keys are not interchangeable: the address bar's key was made for the page you
 * are on, and `mui/index/render` rejects it. The page DOES however contain
 * `mui/index/render/key/<hash>/` inside the grid's own jsLayout/update_url JSON,
 * generated by the backend for that route. Reading it from there is the only way
 * to get a key we cannot compute (the salt is server-side).
 */
const GRID_KEY_PATTERN = /mui[\\/]+index[\\/]+render[\\/]+key[\\/]+([a-f0-9]{16,})/;
/** Storage key for the last key seen, per admin origin+frontname. */
const GRID_KEY_STORAGE = 'mhx:adminkey';

function adminBaseKey(): string {
  const adminPath = location.pathname.match(/^(\/[^/]+\/)/)?.[1] ?? '/';
  return `${GRID_KEY_STORAGE}:${location.origin}${adminPath}`;
}

/** Scan the page for the grid key the admin emitted for this route. */
function gridKeyFromDom(): string {
  const nodes = document.querySelectorAll<HTMLScriptElement>('script');
  for (const node of nodes) {
    const text = node.textContent ?? '';
    if (!text.includes('render')) continue;
    const hit = GRID_KEY_PATTERN.exec(text);
    if (hit?.[1]) return hit[1];
  }
  // The jsLayout can also be an attribute value rather than a script body.
  const attrs = document.querySelectorAll('[data-mage-init], [data-bind], [data-role]');
  for (const node of attrs) {
    for (const attr of Array.from(node.attributes)) {
      if (!attr.value.includes('render')) continue;
      const hit = GRID_KEY_PATTERN.exec(attr.value);
      if (hit?.[1]) return hit[1];
    }
  }
  return '';
}

/**
 * The grid key, from storage when we have already seen one.
 *
 * The key is per route, so one captured on any product grid page is valid for
 * every later query to the same route, on any admin tab. Magento invalidates it
 * with the session; a rejected key is simply retried against the live page.
 */
async function storedGridKey(): Promise<string> {
  try {
    const key = adminBaseKey();
    const value = (await chrome.storage.local.get([key]))[key];
    return typeof value === 'string' ? value : '';
  } catch {
    return '';
  }
}

async function rememberGridKey(key: string): Promise<void> {
  if (!key) return;
  try {
    await chrome.storage.local.set({ [adminBaseKey()]: key });
  } catch {
    // Storage is a convenience here; a failure only costs a page scan.
  }
}

/**
 * The admin grid AJAX endpoint, in the order worth trying.
 *
 * 1. the key the admin emitted for `mui/index/render` itself (most likely valid);
 * 2. the unkeyed route, in case a theme redirects to the right key;
 * 3. the address-bar key, which usually fails validation but costs one request.
 */
function gridBaseUrls(keys: string[]): string[] {
  const adminPath = location.pathname.match(/^(\/[^/]+\/)/)?.[1] ?? '/';
  const base = `${location.origin}${adminPath}mui/index/render`;
  const urls: string[] = [];
  for (const key of keys) {
    const url = `${base}/key/${key}/`;
    if (key && !urls.includes(url)) urls.push(url);
  }
  urls.push(`${base}/`);
  return urls;
}

/**
 * Read a grid AJAX response: its rows, and the reason it has none.
 *
 * Magento answers a rejected filter with `{error: true, message: "..."}` and no
 * `items` at all. Treating that as "zero rows" is what made a broken filter look
 * like a missing product, so the message is carried out instead of dropped.
 */
function readGridResponse(
  text: string,
  status: number,
): { items: GridItem[]; error: string; status: number } {
  try {
    const data = JSON.parse(text) as {
      items?: GridItem[];
      data?: { items?: GridItem[] };
      error?: unknown;
      message?: string;
    };
    const items = data.items ?? data.data?.items ?? [];
    if (data.error && items.length === 0) {
      return {
        items: [],
        error: `Grid rejected the filter: ${data.message ?? 'no message'}`,
        status,
      };
    }
    return { items, error: '', status };
  } catch {
    return {
      items: [],
      error: `Grid returned non-JSON (status ${status}) - the admin session may have expired`,
      status,
    };
  }
}

/**
 * Run one grid query, trying each acceptable endpoint form.
 *
 * Only an error (rejected key, expired session, non-JSON) is retried on the next
 * form; an empty-but-valid answer is final, because that is a real result.
 */
/**
 * The parent product's status straight off the edit page.
 *
 * A disabled SKU has no storefront page, so this (and the grid's Status column)
 * are the only evidence that it is disabled at all - worth reading whenever the
 * page happens to be the one open.
 */
function readPageStatus(): string {
  const el = document.querySelector<HTMLSelectElement>(
    'select#status, select[name="product[status]"]',
  );
  if (el) {
    const text = (el.options[el.selectedIndex]?.text ?? '').trim();
    if (text) return /disab|inactiv|desactiv/i.test(text) ? 'Disabled' : 'Enabled';
  }
  const chk = document.querySelector<HTMLInputElement>(
    'input[name="product[status]"], input#status',
  );
  if (chk) {
    if (chk.type === 'checkbox') return chk.checked ? 'Enabled' : 'Disabled';
    if (chk.value === '1') return 'Enabled';
    if (chk.value === '0') return 'Disabled';
  }
  return '';
}

/** The product edit page's own `type_id`, without trusting a default. */
function readPageType(): string {
  const input = document.querySelector<HTMLInputElement>(
    'input[name="product[type_id]"], input[name="type"], [data-form-part="product_form"][name*="type_id"]',
  );
  const value = (input?.value ?? '').toLowerCase().trim();
  if (value.includes('config')) return 'configurable';
  return value;
}

/** The admin form key lives in the DOM input, or on `window.FORM_KEY`. */
function readFormKey(): string {
  const input = document.querySelector<HTMLInputElement>(
    'input[name="form_key"]',
  );
  if (input?.value) return input.value;
  const win = window as unknown as { FORM_KEY?: string };
  return typeof win.FORM_KEY === 'string' ? win.FORM_KEY : '';
}

/**
 * Run one grid query. The grid endpoint is a POST: the captured request is
 * `POST /mui/index/render/key/<hash>/?isAjax=true` with every parameter in the
 * form body. Sending it as a GET with a query string - what this used to do -
 * never carried the filters at all.
 */
async function gridFetch(
  body: URLSearchParams,
): Promise<{ items: GridItem[]; error: string; status: number }> {
  const failures: string[] = [];
  let last = { items: [] as GridItem[], error: '', status: 0 };
  const domKey = gridKeyFromDom();
  if (domKey) await rememberGridKey(domKey);
  const pageKey = location.href.match(/\/key\/([a-f0-9]{16,})\//)?.[1] ?? '';
  const keys = [domKey, await storedGridKey(), pageKey].filter(Boolean);
  const bases = gridBaseUrls(keys);
  for (const base of bases) {
    try {
      const res = await fetch(`${base}?isAjax=true`, {
        method: 'POST',
        credentials: 'include',
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8',
          'X-Requested-With': 'XMLHttpRequest',
          Accept: 'application/json',
        },
        body: body.toString(),
      });
      const out = readGridResponse(await res.text(), res.status);
      if (!out.error) return out;
      last = out;
      failures.push(out.error);
    } catch (err) {
      last = { items: [], error: (err as Error).message, status: 0 };
      failures.push(last.error);
    }
  }
  // Report every endpoint tried: a single message hid whether the key, the
  // route, or the session was at fault.
  const unique = [...new Set(failures.filter(Boolean))];
  // No key on this page means no admin route emitted one here, which is not a
  // filter problem: either the session is signed out (the login page has no grid
  // key) or the page is not a product grid.
  const hint =
    domKey || keys.length > 1
      ? ''
      : 'no admin grid key on this page - the admin session may be signed out; ';
  return {
    items: last.items,
    error: hint + (unique.join(' / ') || 'the admin grid could not be queried'),
    status: last.status,
  };
}

/**
 * Query the product listing grid by SKU.
 *
 * UI component grids take filters in their own form - `filters[sku]=<term>` - and
 * the column's configured filter decides the operator (text -> `like`). The
 * REST-style `filters[sku][value]` / `[condition_type]` pair used here before is
 * not what the grid parses: it answered with zero rows and no error, so every
 * lookup looked like a missing product.
 */
async function queryGrid(
  sku: string,
  pageSize: number,
): Promise<{ items: GridItem[]; error: string; status: number }> {
  const body = new URLSearchParams();
  body.append('namespace', 'product_listing');
  body.append('form_key', readFormKey());
  body.append('filters[placeholder][]', 'true');
  body.append('filters[sku]', sku);
  body.append('paging[pageSize]', String(pageSize));
  body.append('paging[currentPage]', '1');
  body.append('sorting[field]', 'entity_id');
  body.append('sorting[direction]', 'asc');

  return gridFetch(body);
}

/**
 * Query the product listing grid by numeric entity_id range.
 * Magento's product listing entity_id column is a from/to range filter.
 */
async function queryGridByIds(
  ids: string[],
): Promise<{ items: GridItem[]; error: string; status: number }> {
  if (ids.length === 0) return { items: [], error: '', status: 200 };
  const numeric = ids
    .map((id) => Number(id))
    .filter((n) => Number.isFinite(n) && n > 0);
  if (numeric.length === 0) return { items: [], error: '', status: 200 };
  const min = Math.min(...numeric);
  const max = Math.max(...numeric);
  if (max - min > 500) return { items: [], error: 'Range too wide', status: 200 };

  const body = new URLSearchParams();
  body.append('namespace', 'product_listing');
  body.append('form_key', readFormKey());
  body.append('filters[placeholder][]', 'true');
  body.append('filters[entity_id][from]', String(min));
  body.append('filters[entity_id][to]', String(max));
  body.append('paging[pageSize]', String(Math.max(100, numeric.length + 10)));
  body.append('paging[currentPage]', '1');
  body.append('sorting[field]', 'entity_id');
  body.append('sorting[direction]', 'asc');

  return gridFetch(body);
}

/**
 * Read every assigned child (enabled or disabled) from the Configurations
 * matrix of the currently open product edit page.
 *
 * The admin matrix is status-blind, which is exactly why it is used: it is the
 * only available source for a colour/size whose storefront children are all
 * disabled, and therefore missing from the PDP's jsonConfig.
 *
 * Read-only: a collapsed section is reported, never expanded from here.
 */
export async function readConfigurableChildren(
  productId: string,
  allowExpand = false,
): Promise<ConfigChildren> {
  const edit = location.pathname.match(/\/catalog\/product\/edit\/id\/(\d+)/);
  if (!edit) {
    return {
      children: [],
      reason: 'open the parent product edit page to read every child',
    };
  }
  if (productId && edit[1] !== productId) {
    return {
      children: [],
      reason: `product ${productId} is not the one open in this tab`,
    };
  }

  const section = findConfigSection();
  if (!section) {
    return { children: [], reason: 'no Configurations section on this page' };
  }
  if (isCollapsed(section)) {
    if (!allowExpand) {
      return {
        children: [],
        reason: 'Configurations section is collapsed - expand it and resolve again',
      };
    }
    await expandConfigSection(section);
  }

  const table = section.querySelector<HTMLTableElement>(
    'table.admin__dynamic-rows, table.data-grid, table',
  );
  if (!table) {
    return { children: [], reason: 'no configuration rows yet' };
  }

  const header = Array.from(table.querySelectorAll('thead th')).map((th) =>
    (th.textContent ?? '').trim().toLowerCase(),
  );
  const col = (...names: string[]): number =>
    header.findIndex((h) => names.some((n) => h.includes(n)));
  const attrCol = col('attribute');
  const skuCol = col('sku');
  const statusCol = col('status');
  const attrIndex = attrCol >= 0 ? attrCol : 7;

  const children: ResolverChild[] = [];
  for (const row of Array.from(table.querySelectorAll('tbody tr'))) {
    if (
      row.classList.contains('empty-text') ||
      row.classList.contains('data-grid-tr-no-data')
    ) {
      continue;
    }
    const cells = Array.from(row.querySelectorAll('td'));
    if (cells.length === 0) continue;

    const attrText = (cells[attrIndex]?.textContent ?? '').trim();
    const color =
      attrText.match(/(?:colou?r|cor)\s*:\s*([^,]+)/i)?.[1]?.trim() ?? '';
    const size =
      attrText.match(/(?:size|talla|tamanho|taille)\s*:\s*([^,]+)/i)?.[1]?.trim() ??
      '';

    const link = row.querySelector<HTMLAnchorElement>(CHILD_LINK);
    const id = link?.href.match(/\/edit\/id\/(\d+)/)?.[1] ?? '';
    if (!id) continue;

    const skuCell = skuCol >= 0 ? cells[skuCol] : undefined;
    const skuInput =
      skuCell?.querySelector<HTMLInputElement>('input, textarea') ??
      row.querySelector<HTMLInputElement>(
        'input[name*="[sku]"], [data-index="sku"] input',
      );
    const sku = (skuInput ? skuInput.value : skuCell?.textContent ?? '').trim();

    const statusCell = statusCol >= 0 ? cells[statusCol] : undefined;
    const statusSelect = statusCell?.querySelector<HTMLSelectElement>('select');
    const statusText = (
      statusSelect
        ? statusSelect.options[statusSelect.selectedIndex]?.text ?? ''
        : statusCell?.textContent ?? ''
    ).trim();
    const enabled = statusText
      ? !/disab|inactiv|desactiv/i.test(statusText)
      : undefined;

    children.push({ id, sku, color, size, backend: link?.href ?? '', enabled });
  }

  if (children.length === 0) {
    return {
      children: [],
      reason: 'configuration rows are present but none could be read',
    };
  }
  return { children, reason: '' };
}

/** Page size for the parent-SKU query; also its "filter ignored" threshold. */
const PARENT_SKU_PAGE_SIZE = 200;

/**
 * Query the grid for the children of a configurable product.
 *
 * The product grid carries a `Parent SKU` column, so one filtered request
 * returns every child - enabled or disabled - with its own SKU. That is what a
 * disabled SKU needs: there is no storefront page and often no SKU Library row,
 * so the Configurations matrix was the only other option, and it requires the
 * parent's edit page to be open.
 */
async function queryGridByParentSku(
  parentSku: string,
): Promise<{ items: GridItem[]; error: string; status: number }> {
  const body = new URLSearchParams();
  body.append('namespace', 'product_listing');
  body.append('form_key', readFormKey());
  body.append('filters[placeholder][]', 'true');
  body.append('filters[parent_sku]', parentSku);
  // A deliberately large page: if the filter is ignored, the grid answers with a
  // full page of unrelated products, which is how that is detected below.
  body.append('paging[pageSize]', String(PARENT_SKU_PAGE_SIZE));
  body.append('paging[currentPage]', '1');
  body.append('sorting[field]', 'entity_id');
  body.append('sorting[direction]', 'asc');

  return gridFetch(body);
}

/**
 * Children of `parentSku`, or null when the answer cannot be trusted.
 *
 * Two guards: a full page means the filter was ignored and these are arbitrary
 * products, and when the rows expose `parent_sku` themselves it must match.
 */
function childrenByParentSku(
  items: GridItem[],
  parentSku: string,
  requestedSku: string,
): ResolverChild[] | null {
  if (items.length === 0) return null;
  if (items.length >= PARENT_SKU_PAGE_SIZE) return null;
  const wanted = parentSku.trim().toUpperCase();
  const verified = items.filter((item) => {
    const own = cellText(item, 'parent_sku').toUpperCase();
    return own === '' || own === wanted;
  });
  const derived = childrenFromGrid(verified, requestedSku);
  return derived.length > 0 ? derived : null;
}

/**
 * Child rows as the grid reports them. No colour/size labels (the grid has no
 * such columns), but the child SKU and its status - which is what a human
 * searches for in Magento - are real.
 */
function childrenFromGrid(
  items: GridItem[],
  parentSku: string,
  childIds?: string[],
  prefix?: string,
): ResolverChild[] {
  const wanted = parentSku.trim().toUpperCase();
  const idSet = childIds && childIds.length > 0 ? new Set(childIds) : null;
  const wantPrefix = (prefix ?? '').trim().toUpperCase();
  const out: ResolverChild[] = [];
  for (const item of items) {
    const sku = cellText(item, 'sku');
    if (!sku || sku.toUpperCase() === wanted) continue;
    // A `like` search also returns other products' children (R0317 also matches
    // R03170). Without an explicit id list, require the shared base prefix.
    if (!idSet && wantPrefix && !sku.toUpperCase().startsWith(wantPrefix)) {
      continue;
    }
    const id = itemId(item);
    if (!id) continue;
    if (idSet && !idSet.has(id)) continue;
    out.push({
      id,
      sku,
      color: '',
      size: '',
      backend: '',
      enabled: statusEnabled(item.status ?? item.data?.status),
    });
  }
  return out;
}

/**
 * Search the open admin tab's product grid via AJAX.
 *
 * The grid's SKU column is the product's *own* SKU. In this catalogue the
 * configurable parent is not stored under the code the storefront and the
 * resolver use: `R0317C` is the parent reference, while the rows carry the
 * children's SKUs (`R0317-02-04`). Requiring an exact parent match therefore
 * made one unmatched parent hide every real child, so the parent is now
 * best-effort and the children are read first, from the ids the storefront
 * already resolved.
 */
export async function handleSearchMagento(
  sku: string,
  childIds?: string[],
  parentId?: string,
  expand = false,
  readFacts = false,
): Promise<SearchMagentoResponse> {
  // The parent's own edit page is the best possible source: the Configurations
  // matrix lists every assigned child whether enabled or disabled, with labels,
  // and it needs neither a grid query nor a route secret key.
  const open = location.pathname.match(/\/catalog\/product\/edit\/id\/(\d+)/);
  const openId = open?.[1];
  const pageSku = readPageSku();
  const isTargetPage =
    openId &&
    ((parentId && openId === parentId) ||
      (!parentId && pageSku && pageSku.toUpperCase() === sku.toUpperCase()));

  if (isTargetPage) {
    const targetId = parentId || openId;
    const matrix = await readConfigurableChildren(targetId, expand);
    // PP and categories are not in the matrix, but they are on the same page.
    // Reading them here means a disabled SKU gets real Magento values instead
    // of a Notion-only guess.
    const facts = readFacts
      ? await readAdminFacts({ activateCategoryTab: expand, expandPricing: expand })
      : null;
    if (matrix.children.length > 0 || facts) {
      return {
        found: true,
        productId: targetId,
        sku: pageSku || sku,
        // The edit page knows the parent's own status; the grid is not the
        // only witness, and for a disabled SKU this is the only one we get.
        status: readPageStatus(),
        productType: readPageType() || (matrix.children.length > 0 ? 'configurable' : ''),
        children: matrix.children,
        childrenReason: matrix.children.length > 0 ? '' : matrix.reason,
        magentoFacts: facts ?? undefined,
      };
    }
  }

  const stripped = sku.replace(/[-_\s]?[A-Za-z]+$/, '');

  // 1. Children first: the storefront named exactly which rows to read, so the
  // parent row is not needed to answer this part.
  let children: ResolverChild[] = [];
  let childrenReason = '';
  if (childIds && childIds.length > 0) {
    const byIds = await queryGridByIds(childIds);
    const derived = childrenFromGrid(byIds.items, sku, childIds);
    if (derived.length > 0) {
      children = derived;
      childrenReason = 'child rows read from the product grid by entity id';
    } else if (byIds.error) {
      childrenReason = `grid lookup by child id failed: ${byIds.error}`;
    }
  }

  // 2. Parent row, best-effort. `like` matches every SKU containing the term,
  // so only an exact SKU is the product itself; the stripped suffix
  // (R0317C -> R0317) and the numeric core are the catalogue's own fallbacks.
  const terms = [sku];
  if (stripped && stripped !== sku) terms.push(stripped);
  const numMatch = /(\d{4,})/.exec(sku)?.[1];
  if (numMatch && !terms.includes(numMatch)) terms.push(numMatch);
  const childPrefix = stripped || sku;

  let match: GridItem | undefined;
  let firstItems: GridItem[] = [];
  let firstError = '';
  for (const term of terms) {
    const res = await queryGrid(term, 100);
    if (firstItems.length === 0) firstItems = res.items;
    if (res.error && !firstError) firstError = res.error;
    const exact = res.items.find(
      (item) => cellText(item, 'sku').toUpperCase() === term.toUpperCase(),
    );
    if (exact) {
      match = exact;
      break;
    }
    if (children.length === 0) {
      const derived = childrenFromGrid(res.items, sku, undefined, childPrefix);
      if (derived.length > 0) {
        children = derived;
        childrenReason = `child rows read from the product grid via "${term}"`;
      }
    }
  }

  const productId = match ? itemId(match) : '';

  // 3. Children of the matched parent, by its `Parent SKU` column. This works on
  // any product grid page - no edit page, no Configurations matrix - which is
  // what makes it usable for a disabled SKU.
  if (productId && children.length === 0) {
    const parentSkuValue = cellText(match, 'sku');
    if (parentSkuValue) {
      const byParent = await queryGridByParentSku(parentSkuValue);
      const derived = childrenByParentSku(byParent.items, parentSkuValue, sku);
      if (derived) {
        children = derived;
        childrenReason = `child rows read from the product grid by parent SKU ${parentSkuValue}`;
      } else {
        childrenReason = byParent.error
          ? `parent SKU query failed: ${byParent.error}`
          : `no child rows came back for parent SKU ${parentSkuValue} (${byParent.items.length} row(s) returned)`;
      }
    }
  }

  // 4. The Configurations matrix on the parent's open edit page: the only source
  // with colour/size labels, and status-blind.
  if (productId && children.length === 0) {
    const config = await readConfigurableChildren(productId, expand);
    if (config.children.length > 0) {
      children = config.children;
      childrenReason = '';
    } else if (!childrenReason) {
      childrenReason = config.reason;
    }
  }

  // Only a total miss is a miss: children without their parent row is the
  // normal case when the parent is stored under a different SKU.
  if (productId || children.length > 0) {
    return {
      found: true,
      productId,
      sku: cellText(match, 'sku') || sku,
      status: statusLabel(match?.status ?? match?.data?.status),
      productType: cellText(match, 'type_id'),
      children,
      childrenReason,
    };
  }

  if (firstError && firstItems.length === 0) {
    return { found: false, error: firstError };
  }
  const close = firstItems
    .map((item) => cellText(item, 'sku'))
    .filter(Boolean)
    .slice(0, 6)
    .join(', ');
  return {
    found: false,
    error: close
      ? `SKU "${sku}" has no exact row in the admin grid; the like-filter returned: ${close}.`
      : `SKU "${sku}" not found in the admin grid.`,
  };
}
